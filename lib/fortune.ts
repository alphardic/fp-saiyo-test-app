const ROKUSEI_STAR_BASE = [
  { min: 1, max: 10, name: "土星人" },
  { min: 11, max: 20, name: "金星人" },
  { min: 21, max: 30, name: "火星人" },
  { min: 31, max: 40, name: "天王星人" },
  { min: 41, max: 50, name: "木星人" },
  { min: 51, max: 60, name: "水星人" },
];

// 干支インデックス(0=子,1=丑,...,11=亥) → 霊合星人ペア判定用
// 霊合星人ペア: 土星人+×戌, 土星人-×亥, 金星人+×申, 金星人-×酉,
//               火星人+×午, 火星人-×未, 天王星人+×辰, 天王星人-×巳,
//               木星人+×寅, 木星人-×卯, 水星人+×子, 水星人-×丑
const ZODIAC = ["子", "丑", "寅", "卯", "辰", "巳", "午", "未", "申", "酉", "戌", "亥"];

const REIGOU_PAIRS: Record<string, string> = {
  "土星人+": "戌",
  "土星人-": "亥",
  "金星人+": "申",
  "金星人-": "酉",
  "火星人+": "午",
  "火星人-": "未",
  "天王星人+": "辰",
  "天王星人-": "巳",
  "木星人+": "寅",
  "木星人-": "卯",
  "水星人+": "子",
  "水星人-": "丑",
};

export interface RokuseiResult {
  star: string; // 例: "火星人"
  sign: "+" | "-";
  label: string; // 例: "火星人マイナス"
  reigou: boolean;
}

/** 六星占術の運命星を計算する(1950〜2030年生まれのみ対応)。 */
export function getRokuseiSenjutsu(birthdate: Date): RokuseiResult | null {
  if (!birthdate || Number.isNaN(birthdate.getTime())) return null;

  const year = birthdate.getFullYear();
  const month = birthdate.getMonth() + 1;
  const day = birthdate.getDate();

  const monthTable = ROKUSEI_TABLE[year];
  if (!monthTable) return null;

  const unmeisu = monthTable[month - 1];
  let hoshisu = unmeisu - 1 + day;
  if (hoshisu >= 61) hoshisu -= 60;
  if (hoshisu < 1) hoshisu += 60;

  const baseEntry = ROKUSEI_STAR_BASE.find((r) => hoshisu >= r.min && hoshisu <= r.max);
  if (!baseEntry) return null;

  const zodiacIndex = (((year - 4) % 12) + 12) % 12;
  const zodiac = ZODIAC[zodiacIndex];
  const sign: "+" | "-" = zodiacIndex % 2 === 0 ? "+" : "-";

  const key = `${baseEntry.name}${sign}`;
  const reigou = REIGOU_PAIRS[key] === zodiac;

  const signLabel = sign === "+" ? "プラス" : "マイナス";

  return {
    star: baseEntry.name,
    sign,
    label: `${baseEntry.name}${signLabel}`,
    reigou,
  };
}